"""Fails when the line coverage of a Cobertura report is below a threshold.

Usage: check-coverage.py REPORT MINIMUM_PERCENT
Code generated by source generators (regular expressions) is left out: it is not ours to test.
"""
import sys
import xml.etree.ElementTree as ET

report, minimum = sys.argv[1], float(sys.argv[2])
total = covered = 0
for cls in ET.parse(report).getroot().iter("class"):
    if "RegexGenerator" in cls.get("name", ""):
        continue
    for line in cls.iter("line"):
        total += 1
        covered += int(line.get("hits", "0")) > 0

percent = 100 * covered / total if total else 0
print(f"Line coverage: {percent:.1f} % ({covered}/{total}), minimum {minimum:.0f} %")
sys.exit(0 if percent >= minimum else 1)
